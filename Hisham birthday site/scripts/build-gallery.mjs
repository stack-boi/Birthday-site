/* Build assets/gallery/photos.js from the files in this folder.
 *
 * Add photos (jpg, jpeg, png, webp, avif, gif, svg) or videos (mp4, webm,
 * ogv, m4v, mov) to assets/gallery/, optionally give them a caption in
 * captions.json, then run:
 *
 *   npm run gallery
 *
 * Netlify runs this automatically on deploy (see netlify.toml).
 * Files are ordered by filename, so numeric prefixes control the reel order.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const galleryDir = path.dirname(fileURLToPath(import.meta.url));
const galleryFolder = path.join(galleryDir, "..", "assets", "gallery");
const imageExtensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif", ".svg"]);
const videoExtensions = new Set([".mp4", ".webm", ".ogv", ".m4v", ".mov"]);
const mediaExtensions = new Set([...imageExtensions, ...videoExtensions]);

let captions = {};
try {
  captions = JSON.parse(await readFile(path.join(galleryFolder, "captions.json"), "utf8"));
} catch (error) {
  if (error.code !== "ENOENT") {
    console.warn("Could not read captions.json:", error.message);
  }
}

const entries = await readdir(galleryFolder, { withFileTypes: true });
const files = entries
  .filter((entry) => entry.isFile() && mediaExtensions.has(path.extname(entry.name).toLowerCase()))
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));

const photos = files.map((file) => {
  const meta = typeof captions[file] === "string" ? { caption: captions[file] } : captions[file] || {};
  const extension = path.extname(file).toLowerCase();
  const fallback = path
    .basename(file, extension)
    .replace(/^\d+[-_ ]*/, "")
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());

  const caption = meta.caption || fallback;
  return {
    src: `assets/gallery/${file}`,
    type: videoExtensions.has(extension) ? "video" : "image",
    caption,
    alt: meta.alt || caption
  };
});

const output = `/* Auto-generated by scripts/build-gallery.mjs — do not edit by hand. */\nwindow.HISHAM_GALLERY = ${JSON.stringify(photos, null, 2)};\n`;

await writeFile(path.join(galleryFolder, "photos.js"), output, "utf8");
const videoCount = photos.filter((photo) => photo.type === "video").length;
const photoCount = photos.length - videoCount;
console.log(`Gallery manifest: ${photoCount} photo(s), ${videoCount} video(s) -> assets/gallery/photos.js`);
